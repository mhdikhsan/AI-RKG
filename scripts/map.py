"""Map: run the RML mappings with Morph-KGC and write deterministic N-Triples to build/.

Outputs
  build/imported_risks_{ibm,mit,owasp}.nt  one file per catalogue (licence separation)
  build/imported_crosswalks.nt             SKOS links between imported risks (Nexus, Apache-2.0)
  build/imported_mitigations.nt            MIT controls (CC BY 4.0)
  build/manual_mitigation_links.nt         author-curated risk-mitigation links (only if staging file exists)
  build/accepted_mitigation_links.nt       reviewed LLM candidates (only if staging file exists)
  build/accepted_motifs.nt                 reviewed LLM risk motifs (only if staging files exist)
  build/dataset.ttl                        DCAT/VoID description of every file above
  build/reports/map_checks.md              triple counts + checks
"""
from __future__ import annotations

import re
from collections import Counter, defaultdict

import morph_kgc
from rdflib import RDF, XSD, Graph, Literal, Namespace, URIRef
from rdflib.namespace import DCAT, DCTERMS, SKOS, VOID

from scripts.common import (BUILD, MAPPINGS, REPORTS, ROOT, STAGING, load_config, log, manifest,
                            provenance_line, read_csv, write_text)

PROV = Namespace("http://www.w3.org/ns/prov#")
SKOS_MATCH = {SKOS.exactMatch, SKOS.closeMatch, SKOS.relatedMatch, SKOS.broadMatch, SKOS.narrowMatch}


def materialize(mapping: str) -> Graph:
    cfg = (
        "[CONFIGURATION]\n"
        "logging_level=ERROR\n"
        "na_values=,\n"            # only empty cells are NULL (default also drops the string 'nan')
        "number_of_processes=1\n"
        f"[source]\nmappings={(MAPPINGS / mapping).as_posix()}\n"
    )
    return morph_kgc.materialize(cfg)


def to_nt(g: Graph) -> str:
    """Sorted, de-duplicated N-Triples: byte-identical for identical graphs (no blank nodes here)."""
    lines = {l for l in g.serialize(format="nt", encoding="utf-8").decode("utf-8").splitlines() if l.strip()}
    return "\n".join(sorted(lines)) + ("\n" if lines else "")


def write_graph(name: str, g: Graph) -> int:
    write_text(BUILD / name, to_nt(g))
    return len(g)


def subgraph(g: Graph, subjects: set) -> Graph:
    out = Graph()
    for t in g:
        if t[0] in subjects:
            out.add(t)
    return out


def check_scheme(g: Graph, pattern: re.Pattern, label: str, problems: list) -> None:
    bad = sorted({str(s) for s in g.subjects() if not pattern.match(str(s))})
    if bad:
        problems.append(f"{label}: {len(bad)} subject IRIs do not follow the scheme, e.g. {bad[:3]}")


def check_skos(g: Graph, label: str, problems: list) -> None:
    lit = [(s, p, o) for s, p, o in g if p in SKOS_MATCH and isinstance(o, Literal)]
    if lit:
        problems.append(f"{label}: {len(lit)} literal-valued skos:*Match")


def dataset_description(cfg: dict, files: dict[str, dict]) -> Graph:
    base = cfg["base_iri"]
    m = manifest().get("nexus", {})
    nexus_tree = URIRef(f"https://github.com/IBM/ai-atlas-nexus/tree/{m.get('commit', cfg['sources']['nexus']['commit'])}")
    g = Graph()
    for p, ns in [("dcat", DCAT), ("dct", DCTERMS), ("void", VOID), ("prov", PROV)]:
        g.bind(p, ns)
    for fname, d in sorted(files.items()):
        ds = URIRef(f"{base}dataset/{fname.rsplit('.', 1)[0].replace('_', '-')}")
        g.add((ds, RDF.type, DCAT.Dataset))
        g.add((ds, RDF.type, VOID.Dataset))
        g.add((ds, DCTERMS.title, Literal(d["title"], lang="en")))
        g.add((ds, DCTERMS.identifier, Literal(f"build/{fname}")))
        g.add((ds, DCTERMS.license, URIRef(d["license"])))
        for src in d["sources"]:
            g.add((ds, DCTERMS.source, URIRef(src)))
        g.add((ds, DCTERMS.rightsHolder, Literal(d["rights_holder"])))
        g.add((ds, DCTERMS.bibliographicCitation, Literal(d["attribution"], lang="en")))
        g.add((ds, PROV.wasDerivedFrom, nexus_tree))
        g.add((ds, DCTERMS.description, Literal(
            f"Generated by the AI-RKG core pipeline from IBM AI Atlas Nexus commit {m.get('commit', '')} "
            f"(fetched {m.get('fetched', '')}).", lang="en")))
        if m.get("fetched"):
            g.add((ds, DCTERMS.created, Literal(m["fetched"], datatype=XSD.date)))
        g.add((ds, VOID.triples, Literal(d["triples"], datatype=XSD.integer)))
    return g


def main() -> None:
    if not (STAGING / "risks.csv").exists():
        log("map: staging/risks.csv missing - run stage first; skipped")
        return
    cfg = load_config()
    base = re.escape(cfg["base_iri"])
    BUILD.mkdir(exist_ok=True)
    problems: list[str] = []
    counts: dict[str, int] = {}
    files: dict[str, dict] = {}

    # --- risks, split per catalogue
    risks_rows = read_csv(STAGING / "risks.csv")
    cats = {row["catalogue"] for row in risks_rows}
    g_risks = materialize("risks.rml.ttl")
    counts["risks.rml.ttl"] = len(g_risks)
    check_scheme(g_risks, re.compile(f"^{base}risk/[A-Za-z0-9._-]+$"), "risks", problems)
    check_skos(g_risks, "risks", problems)
    by_cat = defaultdict(set)
    for row in risks_rows:
        by_cat[row["catalogue"]].add(URIRef(row["iri"]))
    catalogues = {c["catalogue"]: c for c in read_csv(STAGING / "catalogues.csv")}
    for cat in sorted(cats):
        name = f"imported_risks_{cat}.nt"
        n = write_graph(name, subgraph(g_risks, by_cat[cat]))
        c = catalogues[cat]
        files[name] = {"title": f"Risks imported from {c['title']}", "license": c["license"],
                       "sources": [c["catalogue_url"]], "rights_holder": c["rights_holder"],
                       "attribution": c["attribution"], "triples": n}
    if sum(files[f"imported_risks_{c}.nt"]["triples"] for c in cats) != len(g_risks):
        problems.append("risks: per-catalogue split lost or duplicated triples")
    # per-entity counts
    risk_count = Counter(row["catalogue"] for row in risks_rows)
    typed = len(set(g_risks.subjects(RDF.type, URIRef(cfg["ak_namespace"] + "Risk"))))
    if typed != len(risks_rows):
        problems.append(f"risks: {typed} typed ak:Risk vs {len(risks_rows)} staged rows")

    # --- crosswalks
    g_xw = materialize("crosswalks.rml.ttl")
    counts["crosswalks.rml.ttl"] = len(g_xw)
    check_scheme(g_xw, re.compile(f"^{base}risk/[A-Za-z0-9._-]+$"), "crosswalks", problems)
    check_skos(g_xw, "crosswalks", problems)
    n_rows = len(read_csv(STAGING / "crosswalks.csv"))
    if len(g_xw) != n_rows:
        problems.append(f"crosswalks: {len(g_xw)} triples vs {n_rows} staged rows")
    write_graph("imported_crosswalks.nt", g_xw)
    xw_files = sorted({r["mapping_file"] for r in read_csv(STAGING / "crosswalks.csv")})
    nexus_raw = f"https://github.com/IBM/ai-atlas-nexus/blob/{manifest().get('nexus', {}).get('commit', '')}/src/ai_atlas_nexus/data/mappings/"
    files["imported_crosswalks.nt"] = {
        "title": "Crosswalks between imported risks (IBM AI Atlas Nexus SSSOM mapping sets)",
        "license": cfg["crosswalk_license"], "sources": [nexus_raw + f for f in xw_files],
        "rights_holder": "IBM Corporation and mapping authors as listed per row in staging/crosswalks.csv",
        "attribution": "Crosswalks from IBM AI Atlas Nexus (Apache-2.0); per-row justification, author and date in staging/crosswalks.csv.",
        "triples": len(g_xw)}

    # --- mitigations
    g_mit = materialize("mitigations.rml.ttl")
    counts["mitigations.rml.ttl"] = len(g_mit)
    check_scheme(g_mit, re.compile(f"^{base}mitigation/[A-Za-z0-9._-]+$"), "mitigations", problems)
    check_skos(g_mit, "mitigations", problems)
    write_graph("imported_mitigations.nt", g_mit)
    mm = cfg["mit_mitigations"]
    files["imported_mitigations.nt"] = {
        "title": "Mitigations imported from the MIT AI Risk Repository (mitigation database and taxonomy)",
        "license": mm["license"], "sources": [mm["source_url"]],
        "rights_holder": cfg["catalogues"]["mit"]["rights_holder"],
        "attribution": "MIT AI Risk Repository mitigation database / Draft AI Risk Mitigation Taxonomy, via IBM AI Atlas Nexus (CC BY 4.0).",
        "triples": len(g_mit)}

    # --- author-curated (reviewed) mitigation links
    manual = STAGING / "manual_mitigation_links.csv"
    if manual.exists() and (MAPPINGS / "manual_mitigation_links.rml.ttl").exists():
        rows = read_csv(manual)
        g_man = materialize("manual_mitigation_links.rml.ttl") if rows else Graph()
        counts["manual_mitigation_links.rml.ttl"] = len(g_man)
        if len(g_man) != len(rows):
            problems.append(f"manual mitigation links: {len(g_man)} triples vs {len(rows)} staged rows")
        write_graph("manual_mitigation_links.nt", g_man)
        mcfg = cfg["manual_mitigation_links"]
        files["manual_mitigation_links.nt"] = {
            "title": "Risk-mitigation links curated and reviewed by the authors",
            "license": mcfg["license"], "sources": [mm["source_url"]],
            "rights_holder": "AI-RKG authors",
            "attribution": f"Curated by the authors ({mcfg['file']}); MIT controls from the MIT AI Risk Repository (CC BY 4.0).",
            "triples": len(g_man)}

    # --- accepted risk motifs (llm_motif), only when reviewed rows exist
    if (STAGING / "accepted_motifs.csv").exists() and (MAPPINGS / "accepted_motifs.rml.ttl").exists():
        rows = read_csv(STAGING / "accepted_motifs.csv")
        g_mot = materialize("accepted_motifs.rml.ttl") if rows else Graph()
        counts["accepted_motifs.rml.ttl"] = len(g_mot)
        n_typed = len(set(g_mot.subjects(RDF.type, URIRef(cfg["ak_namespace"] + "RiskMotif"))))
        if n_typed != len(rows):
            problems.append(f"accepted motifs: {n_typed} typed ak:RiskMotif vs {len(rows)} staged rows")
        write_graph("accepted_motifs.nt", g_mot)
        a = cfg["sources"]["aiid"]
        files["accepted_motifs.nt"] = {
            "title": "Risk motifs proposed by an LLM from AIID incidents and AVID records, accepted by a human reviewer (extractor/llm_motif/)",
            # derived from AIID (CC BY-SA 4.0); share-alike is the stricter of the two source licences
            "license": a["license"], "sources": ["https://incidentdatabase.ai/", cfg["sources"]["avid"]["repo"]],
            "rights_holder": "AI-RKG authors (motifs and review decisions)",
            "attribution": "Derived from the AI Incident Database (CC BY-SA 4.0) and the AI Vulnerability Database (MIT); "
                           "provenance per motif in staging/accepted_motifs.csv.",
            "triples": len(g_mot)}

    # --- accepted LLM mitigation links, only when reviewed rows exist
    if (STAGING / "accepted_mitigation_links.csv").exists() and (MAPPINGS / "accepted_mitigation_links.rml.ttl").exists():
        rows = read_csv(STAGING / "accepted_mitigation_links.csv")
        g_acc = materialize("accepted_mitigation_links.rml.ttl") if rows else Graph()
        counts["accepted_mitigation_links.rml.ttl"] = len(g_acc)
        write_graph("accepted_mitigation_links.nt", g_acc)
        files["accepted_mitigation_links.nt"] = {
            "title": "Human-reviewed mitigation-risk links proposed by an LLM (extractor/llm_mitigation/)",
            "license": mm["license"], "sources": [mm["source_url"]],
            "rights_holder": "AI-RKG authors (review decisions)",
            "attribution": "Candidate links generated with an LLM and accepted by a human reviewer; see staging/accepted_mitigation_links.csv.",
            "triples": len(g_acc)}

    ds = dataset_description(cfg, files)
    write_text(BUILD / "dataset.ttl", ds.serialize(format="turtle"))

    # --- report
    lines = ["# Mapping checks", "", provenance_line(), "",
             "| Mapping | Triples |", "|---|---|"]
    lines += [f"| `{k}` | {v} |" for k, v in counts.items()]
    lines += ["", "| Output file | Triples | Licence |", "|---|---|---|"]
    lines += [f"| `build/{k}` | {v['triples']} | {v['license']} |" for k, v in sorted(files.items())]
    lines += ["", f"Imported risks per catalogue: {dict(sorted(risk_count.items()))}; "
              f"mitigations: {len(set(g_mit.subjects(RDF.type, None)))}.", "",
              "## Checks", "",
              "- subject IRIs follow `{base_iri}risk/{nexus_id}` / `{base_iri}mitigation/{nexus_id}`",
              "- no literal-valued `skos:*Match`",
              "- crosswalk triples = staged rows; typed risks = staged rows", "",
              "Result: " + ("**PASS**" if not problems else "**FAIL**")]
    lines += [f"- {p}" for p in problems]
    write_text(REPORTS / "map_checks.md", "\n".join(lines) + "\n")
    for k, v in counts.items():
        log(f"  {k}: {v} triples")
    for k, v in sorted(files.items()):
        log(f"  build/{k}: {v['triples']} triples")
    if problems:
        for p in problems:
            log(f"  CHECK FAILED: {p}")
        raise SystemExit("map: checks failed")
    log("map: all checks passed")


if __name__ == "__main__":
    main()
